import 'package:muhasib/features/sales/domain/entities/invoice_entity.dart';
import 'invoice_line_model.dart';

class InvoiceModel extends InvoiceEntity {
  const InvoiceModel({
    super.id,
    super.creatorId,
    super.lastModifierId,
    super.concurrencyStamp,
    super.extraProperties,
    super.creationTime,
    super.lastModificationTime,
    required super.invoiceType,
    required super.number,
    required super.date,
    super.statement,
    required super.amount,
    super.totalAmount,
    super.taxAmt,
    super.taxRatio,
    super.discountAmt,
    super.discountRatio,
    super.otherFeeAmt,
    super.otherFeeNetRatio,
    super.netRevenueAmt,
    super.totalAmountAfterDiscount,
    super.finalAmt,
    super.currencyId,
    required super.stockId,
    required super.customerId,
    super.taxId,
    super.otherFeeAccountId,
    required super.invoiceTransType,
    super.parentInvoiceType,
    super.parentInvoiceId,
    super.parentInvoiceNumber,
    super.nextInvoiceType,
    super.nextInvoiceId,
    super.nextInvoiceNumber,
    super.uNo,
    super.currencyCode,
    super.exchangeRate,
    super.imagePath,
    super.paymentStatus = 0,
    super.shippingAddress,
    super.dueDate,
    super.quotationStatus,
    super.paidAmount,
    super.bankPaidAmount,
    List<InvoiceLineModel> lines = const [],
  }) : super(lines: lines);

  factory InvoiceModel.fromJson(
    Map<String, dynamic> json, {
    List<InvoiceLineModel> lines = const [],
  }) {
    return InvoiceModel(
      id: json['id'] as int?,
      creatorId: json['creator_id'] as int?,
      lastModifierId: json['last_modifier_id'] as int?,
      concurrencyStamp: json['concurrency_stamp'] as String?,
      extraProperties: json['extra_properties'] as String?,
      creationTime: json['creation_time'] as int?,
      lastModificationTime: json['last_modification_time'] as int?,
      invoiceType: json['invoice_type'] as int,
      number: json['number'] as String,
      date: json['date'] as int,
      statement: json['statement'] as String?,
      amount: (json['amount'] as num).toDouble(),
      totalAmount: (json['total_amount'] as num?)?.toDouble(),
      taxAmt: (json['tax_amt'] as num?)?.toDouble(),
      taxRatio: (json['tax_ratio'] as num?)?.toDouble(),
      discountAmt: (json['discount_amt'] as num?)?.toDouble(),
      discountRatio: (json['discount_ratio'] as num?)?.toDouble(),
      otherFeeAmt: (json['other_fee_amt'] as num?)?.toDouble(),
      otherFeeNetRatio: (json['other_fee_net_ratio'] as num?)?.toDouble(),
      netRevenueAmt: (json['net_revenue_amt'] as num?)?.toDouble(),
      totalAmountAfterDiscount: (json['total_amount_after_discount'] as num?)
          ?.toDouble(),
      finalAmt: (json['final_amt'] as num?)?.toDouble(),
      currencyId: json['currency_id'] as int?,
      stockId: json['stock_id'] as int,
      customerId: json['customer_id'] as int,
      taxId: json['tax_id'] as int?,
      otherFeeAccountId: json['other_fee_account_id'] as int?,
      invoiceTransType: json['invoice_trans_type'] as int,
      parentInvoiceType: json['parent_invoice_type'] as int?,
      parentInvoiceId: json['parent_invoice_id'] as int?,
      parentInvoiceNumber: json['parent_invoice_number'] as String?,
      nextInvoiceType: json['next_invoice_type'] as int?,
      nextInvoiceId: json['next_invoice_id'] as int?,
      nextInvoiceNumber: json['next_invoice_number'] as String?,
      uNo: json['u_no'] as String?,
      currencyCode: json['currency_code'] as String?,
      exchangeRate: (json['exchange_rate'] as num?)?.toDouble(),
      imagePath: json['image_path'] as String?,
      paymentStatus: json['payment_status'] as int? ?? 0,
      shippingAddress: json['shipping_address'] as String?,
      dueDate: json['due_date'] as int?,
      quotationStatus: json['quotation_status'] as int?,
      paidAmount: (json['paid_amount'] as num?)?.toDouble(),
      bankPaidAmount: (json['bank_paid_amount'] as num?)?.toDouble(),
      lines: lines,
    );
  }

  Map<String, dynamic> toJson() {
    final map = <String, dynamic>{
      'id': id,
      'creator_id': creatorId ?? 1,
      'last_modifier_id': lastModifierId ?? 1,
      'concurrency_stamp': concurrencyStamp,
      'extra_properties': extraProperties,
      'invoice_type': invoiceType,
      'number': number,
      'date': date,
      'statement': statement,
      'amount': amount,
      'total_amount': totalAmount,
      'tax_amt': taxAmt,
      'tax_ratio': taxRatio,
      'discount_amt': discountAmt,
      'discount_ratio': discountRatio,
      'other_fee_amt': otherFeeAmt,
      'other_fee_net_ratio': otherFeeNetRatio,
      'net_revenue_amt': netRevenueAmt,
      'total_amount_after_discount': totalAmountAfterDiscount,
      'final_amt': finalAmt,
      'currency_id': currencyId,
      'stock_id': stockId,
      'customer_id': customerId,
      'tax_id': taxId,
      'other_fee_account_id': otherFeeAccountId,
      'invoice_trans_type': invoiceTransType,
      'parent_invoice_type': parentInvoiceType,
      'parent_invoice_id': parentInvoiceId,
      'parent_invoice_number': parentInvoiceNumber,
      'next_invoice_type': nextInvoiceType,
      'next_invoice_id': nextInvoiceId,
      'next_invoice_number': nextInvoiceNumber,
      'u_no': uNo,
      'currency_code': currencyCode,
      'exchange_rate': exchangeRate,
      'image_path': imagePath,
      'payment_status': paymentStatus,
      'shipping_address': shippingAddress,
      'due_date': dueDate,
      'quotation_status': quotationStatus,
      'paid_amount': paidAmount,
      'bank_paid_amount': bankPaidAmount,
    };
    if (creationTime != null) {
      map['creation_time'] = creationTime;
    }
    if (lastModificationTime != null) {
      map['last_modification_time'] = lastModificationTime;
    }
    return map;
  }

  InvoiceEntity toEntity() => InvoiceEntity(
    id: id,
    creatorId: creatorId,
    lastModifierId: lastModifierId,
    concurrencyStamp: concurrencyStamp,
    extraProperties: extraProperties,
    creationTime: creationTime,
    lastModificationTime: lastModificationTime,
    invoiceType: invoiceType,
    number: number,
    date: date,
    statement: statement,
    amount: amount,
    totalAmount: totalAmount,
    taxAmt: taxAmt,
    taxRatio: taxRatio,
    discountAmt: discountAmt,
    discountRatio: discountRatio,
    otherFeeAmt: otherFeeAmt,
    otherFeeNetRatio: otherFeeNetRatio,
    netRevenueAmt: netRevenueAmt,
    totalAmountAfterDiscount: totalAmountAfterDiscount,
    finalAmt: finalAmt,
    currencyId: currencyId,
    stockId: stockId,
    customerId: customerId,
    taxId: taxId,
    otherFeeAccountId: otherFeeAccountId,
    invoiceTransType: invoiceTransType,
    parentInvoiceType: parentInvoiceType,
    parentInvoiceId: parentInvoiceId,
    parentInvoiceNumber: parentInvoiceNumber,
    nextInvoiceType: nextInvoiceType,
    nextInvoiceId: nextInvoiceId,
    nextInvoiceNumber: nextInvoiceNumber,
    uNo: uNo,
    currencyCode: currencyCode,
    exchangeRate: exchangeRate,
    imagePath: imagePath,
    paymentStatus: paymentStatus,
    shippingAddress: shippingAddress,
    dueDate: dueDate,
    quotationStatus: quotationStatus,
    paidAmount: paidAmount,
    bankPaidAmount: bankPaidAmount,
    lines: lines,
  );

  factory InvoiceModel.fromEntity(InvoiceEntity e) => InvoiceModel(
    id: e.id,
    creatorId: e.creatorId,
    lastModifierId: e.lastModifierId,
    concurrencyStamp: e.concurrencyStamp,
    extraProperties: e.extraProperties,
    creationTime: e.creationTime,
    lastModificationTime: e.lastModificationTime,
    invoiceType: e.invoiceType,
    number: e.number,
    date: e.date,
    statement: e.statement,
    amount: e.amount,
    totalAmount: e.totalAmount,
    taxAmt: e.taxAmt,
    taxRatio: e.taxRatio?.toDouble(),
    discountAmt: e.discountAmt,
    discountRatio: e.discountRatio?.toDouble(),
    otherFeeAmt: e.otherFeeAmt,
    otherFeeNetRatio: e.otherFeeNetRatio?.toDouble(),
    netRevenueAmt: e.netRevenueAmt,
    totalAmountAfterDiscount: e.totalAmountAfterDiscount,
    finalAmt: e.finalAmt,
    currencyId: e.currencyId,
    stockId: e.stockId,
    customerId: e.customerId,
    taxId: e.taxId,
    otherFeeAccountId: e.otherFeeAccountId,
    invoiceTransType: e.invoiceTransType,
    parentInvoiceType: e.parentInvoiceType,
    parentInvoiceId: e.parentInvoiceId,
    parentInvoiceNumber: e.parentInvoiceNumber,
    nextInvoiceType: e.nextInvoiceType,
    nextInvoiceId: e.nextInvoiceId,
    nextInvoiceNumber: e.nextInvoiceNumber,
    uNo: e.uNo,
    currencyCode: e.currencyCode,
    exchangeRate: e.exchangeRate,
    imagePath: e.imagePath,
    paymentStatus: e.paymentStatus,
    shippingAddress: e.shippingAddress,
    dueDate: e.dueDate,
    quotationStatus: e.quotationStatus,
    paidAmount: e.paidAmount,
    bankPaidAmount: e.bankPaidAmount,
    lines: e.lines
        .map((l) => l is InvoiceLineModel ? l : InvoiceLineModel.fromEntity(l))
        .toList(),
  );
}
