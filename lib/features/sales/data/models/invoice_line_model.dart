    stockId: stockId,
    invoiceId: invoiceId,
    customerId: customerId,
    date: date,
    expireDate: expireDate,
    invoiceTransType: invoiceTransType,
    lineDiscount: lineDiscount,
    baseQuantity: baseQuantity,
    conversionRate: conversionRate,
    packaging: packaging,
    costPrice: costPrice,
    costTotal: costTotal,
    price: price,
    sellingPrice: sellingPrice,
  );

