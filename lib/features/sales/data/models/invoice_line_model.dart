    totalAmount: e.totalAmount,
    taxAmt: e.taxAmt,
    taxRatio: e.taxRatio,
    discountAmt: e.discountAmt,
    discountRatio: e.discountRatio,
    otherFeeAmt: e.otherFeeAmt,
    otherFeeNetRatio: e.otherFeeNetRatio,
    netRevenueAmt: e.netRevenueAmt,
    currencyCode: e.currencyCode,
    exchangeRate: e.exchangeRate,
    currencyId: e.currencyId,
    quantity: e.quantity,
    categoryId: e.categoryId,
    groupId: e.groupId,
    unitId: e.unitId,
    categorySubUnitId: e.categorySubUnitId,
    stockId: e.stockId,
    invoiceId: e.invoiceId,
    customerId: e.customerId,
    date: e.date,
    expireDate: e.expireDate,
    invoiceTransType: e.invoiceTransType,
    lineDiscount: e.lineDiscount,
    baseQuantity: e.baseQuantity,
    conversionRate: e.conversionRate,
    packaging: e.packaging,
    costPrice: e.costPrice,
    costTotal: e.costTotal,
    price: e.price,
    sellingPrice: e.sellingPrice,
  );
}

