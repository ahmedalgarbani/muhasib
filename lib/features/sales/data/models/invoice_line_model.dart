import 'package:muhasib/features/sales/domain/entities/invoice_line_entity.dart';

class InvoiceLineModel extends InvoiceLineEntity {
  const InvoiceLineModel({
    super.id,
    super.creatorId,
    super.lastModifierId,
    super.concurrencyStamp,
    super.extraProperties,
    super.creationTime,
    super.lastModificationTime,
    required super.invoiceType,
    required super.amount,
    required super.totalAmount,
    super.taxAmt,
    super.taxRatio,
    super.discountAmt,
    super.discountRatio,
    super.otherFeeAmt,
    super.otherFeeNetRatio,
    required super.netRevenueAmt,
    super.currencyCode,
    super.exchangeRate,
    super.currencyId,
    required super.quantity,
    super.categoryId,
    required super.groupId,
    required super.unitId,
    required super.categorySubUnitId,
    required super.stockId,
    required super.invoiceId,
    required super.customerId,
    required super.date,
    super.expireDate,
    required super.invoiceTransType,
    super.lineDiscount,
    // Unit conversion
    super.baseQuantity,
    super.conversionRate,
    super.packaging,
    // Cost tracking
    super.costPrice,
    super.costTotal,
    // Price tracking
    super.price,
    super.sellingPrice,
  });

  factory InvoiceLineModel.fromJson(Map<String, dynamic> json) =>
      InvoiceLineModel(
        id: json['id'] as int?,
        creatorId: json['creator_id'] as int?,
        lastModifierId: json['last_modifier_id'] as int?,
        concurrencyStamp: json['concurrency_stamp'] as String?,
        extraProperties: json['extra_properties'] as String?,
        creationTime: json['creation_time'] as int?,
        lastModificationTime: json['last_modification_time'] as int?,
        invoiceType: json['invoice_type'] as int,
        amount: (json['amount'] as num).toDouble(),
        totalAmount: (json['total_amount'] as num).toDouble(),
        taxAmt: (json['tax_amt'] as num?)?.toDouble(),
        taxRatio: json['tax_ratio'] as int?,
        discountAmt: (json['discount_amt'] as num?)?.toDouble(),
        discountRatio: json['discount_ratio'] as int?,
        otherFeeAmt: (json['other_fee_amt'] as num?)?.toDouble(),
        otherFeeNetRatio: json['other_fee_net_ratio'] as int?,
        netRevenueAmt: (json['net_revenue_amt'] as num).toDouble(),
        currencyCode: json['currency_code'] as String?,
        exchangeRate: (json['exchange_rate'] as num?)?.toDouble(),
        currencyId: json['currency_id'] as int?,
        quantity: (json['quantity'] as num).toDouble(),
        categoryId: json['category_id'] as int?,
        groupId: json['group_id'] as int,
        unitId: json['unit_id'] as int,
        categorySubUnitId: json['category_sub_unit_id'] as int,
        stockId: json['stock_id'] as int,
        invoiceId: json['invoice_id'] as int,
        customerId: json['customer_id'] as int,
        date: json['date'] as int,
        expireDate: json['expire_date'] as int?,
        invoiceTransType: json['invoice_trans_type'] as int,
        lineDiscount: (json['line_discount'] as num?)?.toDouble(),
        // Unit conversion
        baseQuantity: (json['base_quantity'] as num?)?.toDouble(),
        conversionRate: (json['conversion_rate'] as num?)?.toDouble(),
        packaging: json['packaging'] as int?,
        // Cost tracking
        costPrice: (json['cost_price'] as num?)?.toDouble(),
        costTotal: (json['cost_total'] as num?)?.toDouble(),
        // Price tracking
        price: (json['price'] as num?)?.toDouble(),
        sellingPrice: (json['selling_price'] as num?)?.toDouble(),
      );

  Map<String, dynamic> toJson({required int invoiceId}) {
    final map = <String, dynamic>{
      'id': id,
      'creator_id': creatorId ?? 1,
      'last_modifier_id': lastModifierId ?? 1,
      'concurrency_stamp': concurrencyStamp,
      'extra_properties': extraProperties,
      'invoice_type': invoiceType,
      'amount': amount,
      'total_amount': totalAmount,
      'tax_amt': taxAmt,
      'tax_ratio': taxRatio,
      'discount_amt': discountAmt,
      'discount_ratio': discountRatio,
      'other_fee_amt': otherFeeAmt,
      'other_fee_net_ratio': otherFeeNetRatio,
      'net_revenue_amt': netRevenueAmt,
      'currency_code': currencyCode,
      'exchange_rate': exchangeRate,
      'currency_id': currencyId,
      'quantity': quantity,
      'category_id': categoryId,
      'group_id': groupId,
      'unit_id': unitId,
      'category_sub_unit_id': categorySubUnitId,
      'stock_id': stockId,
      'invoice_id': invoiceId,
      'customer_id': customerId,
      'date': date,
      'expire_date': expireDate,
      'invoice_trans_type': invoiceTransType,
      'line_discount': lineDiscount ?? 0.0,
      // Unit conversion
      'base_quantity': baseQuantity ?? quantity,
      'conversion_rate': conversionRate ?? 1.0,
      'packaging': packaging ?? 1,
      // Cost tracking
      'cost_price': costPrice,
      'cost_total': costTotal,
      // Price tracking
      'price': price,
      'selling_price': sellingPrice,
    };
    if (creationTime != null) {
      map['creation_time'] = creationTime;
    }
    if (lastModificationTime != null) {
      map['last_modification_time'] = lastModificationTime;
    }
    return map;
  }

  InvoiceLineEntity toEntity() => InvoiceLineEntity(
    id: id,
    creatorId: creatorId,
    lastModifierId: lastModifierId,
    concurrencyStamp: concurrencyStamp,
    extraProperties: extraProperties,
    creationTime: creationTime,
