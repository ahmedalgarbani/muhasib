import 'package:muhasib/features/products/domain/entities/item_movement_entity.dart';

class ItemMovementModel extends ItemMovementEntity {
  const ItemMovementModel({
    required super.docNo,
    required super.transDocType,
    required super.transInOut,
    required super.transDate,
    required super.categoryId,
    required super.unitId,
    required super.groupId,
    required super.categorySubUnitId,
    required super.stockId,
    super.quantity,
    required super.quantityIn,
    required super.quantityOut,
    super.costAmount,
    super.costLocalAmount,
    required super.currencyId,
    super.currencyCode,
    super.exchangeRate,
    super.sellAmount,
    super.sellLocalAmount,
    required super.refrencNo,
    required super.statement,
    super.referenceNumber,
    super.uNo,
    super.barcodeNo,
    super.expireDate,
    super.customerId,
    super.creatorId,
    super.lastModifierId,
    super.concurrencyStamp,
    super.extraProperties,
    super.creationTime,
    super.lastModificationTime,
  });

  factory ItemMovementModel.fromJson(Map<String, dynamic> json) {
    return ItemMovementModel(
      docNo: json['doc_no'] as int,
      transDocType: json['trans_doc_type'] as int,
      transInOut: (json['trans_in_out'] as int) == 1,
      transDate: json['trans_date'] as int,
      categoryId: json['category_id'] as int,
      unitId: json['unit_id'] as int,
      groupId: json['group_id'] as int,
      categorySubUnitId: json['category_sub_unit_id'] as int,
      stockId: json['stock_id'] as int,
      quantity: (json['quantity'] as num?)?.toDouble(),
      quantityIn: (json['quantity_in'] as num).toDouble(),
      quantityOut: (json['quantity_out'] as num).toDouble(),
      costAmount: (json['cost_amount'] as num?)?.toDouble(),
      costLocalAmount: (json['cost_local_amount'] as num?)?.toDouble(),
      currencyId: json['currency_id'] as int,
      currencyCode: json['currency_code'] as String?,
      exchangeRate: (json['exchange_rate'] as num?)?.toDouble(),
      sellAmount: (json['sell_amount'] as num?)?.toDouble(),
      sellLocalAmount: (json['sell_local_amount'] as num?)?.toDouble(),
      refrencNo: json['refrenc_no'] as String,
      statement: json['statement'] as String,
      referenceNumber: json['reference_number'] as String?,
      uNo: json['u_no'] as String?,
      barcodeNo: json['barcode_no'] as String?,
      expireDate: json['expire_date'] as int?,
      customerId: json['customer_id'] as int?,
      creatorId: json['creator_id'] as int?,
      lastModifierId: json['last_modifier_id'] as int?,
      concurrencyStamp: json['concurrency_stamp'] as String?,
      extraProperties: json['extra_properties'] as String?,
      creationTime: json['creation_time'] as int?,
      lastModificationTime: json['last_modification_time'] as int?,
    );
  }
}
